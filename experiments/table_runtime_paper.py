"""
table_runtime_paper.py
----------------------
Appendix runtime tables of the paper (tabapp_runtime.tex): a one-row "Sweep
total (CPU-h)" table followed by the per-method median wall-clock table, for
the paper's 14 methods and 12+1 tasks (drops dad/qptl/cpLayer and sp_planted;
keeps portfolio as the "excluded task" column).

Input  (results/): runtimes_per_method_task.json
Output (results/tables/): tabapp_runtime.tex

Run from the repo root::

    PYTHONPATH=$PWD python experiments/table_runtime_paper.py
"""

import json
import os

IN_JSON = "results/runtimes_per_method_task.json"
OUT_TEX = "results/tables/tabapp_runtime.tex"

# Paper method set and row order (sec_expt_bench: "9 tasks by 14 methods").
METHODS = ["mse", "mse_train", "mse_val", "dfl", "identity", "spo", "nce",
           "blackbox", "pointLTR", "pairLTR", "listLTR", "lodl", "perturb",
           "pg"]
METHOD_LABELS = {
    "mse": "MSE", "mse_train": r"MSE\textsubscript{tr}",
    "mse_val": r"MSE\textsubscript{val}", "dfl": "DFL",
    "identity": "Identity", "spo": r"SPO\textsuperscript{+}", "nce": "NCE",
    "blackbox": "Blackbox", "pointLTR": "pt-LTR", "pairLTR": "pr-LTR",
    "listLTR": "L-LTR", "lodl": "LODL", "perturb": "DPO", "pg": "PG",
}

# Task groups and abbreviations exactly as in tabapp_tuning_benefit.tex,
# plus the excluded Portfolio task (reported in the paper's appendix).
GROUPS = [
    ("Not recommended", ["knapsack", "knapsack-real", "energy", "cubic",
                         "bipartitematching", "shortestpath"]),
    ("Recommended", ["budgetalloc", "pg_misspec", "sp_synth"]),
    ("Spatiotemp.~Top-K", ["cook_county", "speed_humps", "asurv"]),
    ("Excl.", ["portfolio"]),
]
PROB_LABELS = {
    "knapsack": "KS", "knapsack-real": "KS-E", "energy": "En", "cubic": "Cu",
    "bipartitematching": "BM", "shortestpath": "SP-W", "budgetalloc": "BA",
    "pg_misspec": r"pg\textsubscript{ms}", "sp_synth": r"sp\textsubscript{s}",
    "cook_county": "CC", "speed_humps": "SH", "asurv": "WC",
    "portfolio": "Pf",
}
PROBS = [p for _, ps in GROUPS for p in ps]


def fmt_min(m):
    if m is None:
        return "--"
    if m < 10:
        return f"{m:.1f}"
    if m < 600:
        return f"{m:.0f}"
    return f"{m/60:.1f}h"


def fmt_min(m):
    if m is None:
        return "--"
    if m < 10:
        return f"{m:.1f}"
    if m < 600:
        return f"{m:.0f}"
    return f"{m/60:.1f}h"


def main():
    with open(IN_JSON) as f:
        rt = json.load(f)

    cols = "l" + "r" * len(PROBS)
    header_groups, cmids, start = [], [], 2
    for gname, ps in GROUPS:
        header_groups.append(rf"\multicolumn{{{len(ps)}}}{{c}}{{{gname}}}")
        cmids.append(rf"\cmidrule(lr){{{start}-{start+len(ps)-1}}}")
        start += len(ps)
    group_hdr = " & " + " & ".join(header_groups) + r" \\"
    cmid_hdr = "".join(cmids)

    tot_row, grand_h, grand_runs = ["Sweep total (CPU-h)"], 0.0, 0
    for prob in PROBS:
        tot = sum(rt.get(m, {}).get(prob, {}).get("total_cpu_hours", 0.0)
                  for m in METHODS)
        grand_h += tot
        grand_runs += sum(rt.get(m, {}).get(prob, {}).get("n_runs", 0)
                          for m in METHODS)
        tot_row.append(f"{tot:,.0f}")
    tot_line = " & ".join(tot_row) + r" \\"

    lines = [
        "% Auto-generated by rethink_exp/table_runtime_paper.py — do not edit.",
        "% Data: runtimes_per_method_task.json (rethink_exp/collect_runtimes.py).",
        "",
        "",
        r"\begin{table}[!h]",
        r"\centering",
        r"""\caption{Full wall-clock time required for 2-phase hyperparameter search across all tasks, aggregated over all methods.""",
        r"""For task abbreviations, see Tab.~\ref{tab:tuning-benefit}""",
        r"""}%endcaption""",
        r"""\label{tab:timetotal-per-task}""",
        r"\setlength{\tabcolsep}{3.5pt}",
        r"\footnotesize",
        rf"\begin{{tabular}}{{{cols}}}",
        r"\toprule",
        group_hdr,
        cmid_hdr,
        " & " + " & ".join(PROB_LABELS[p] for p in PROBS) + r" \\",
        tot_line,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
        "",
        r"\begin{table}[!h]",
        r"\centering",
        r"""\caption{Median wall-clock training time per run of the validation-selected configuration, over the 10 runs from distinct random initializations. """,
        r"""Unmarked times are reported in minutes,""",
        r"""times with suffix `h` are reported in hours.""",
        r"""Times are reconstructed from per-epoch log timestamps with scheduler preemption gaps excised; each run uses 2 CPU cores and 8\,GB RAM (Warcraft shortest path adds one GPU). Times include the per-epoch validation solver evaluation that drives checkpoint selection, except for MSE\textsubscript{tr}, MSE\textsubscript{val} (which select on prediction error by design). """,
        r"""For task abbreviations, see Tab.~\ref{tab:tuning-benefit}.""",
        r"""%Runs train at most 300 epochs with patience 40. """,
        r"""%The bottom row totals every Phase-1 and Phase-2 run behind the paper's results, i.e.\ the full cost of the hyperparameter search. `--': method not applicable.""",
        r"""}""",
        r"""\label{tab:runtime-per-method-task}""",
        r"\setlength{\tabcolsep}{3.5pt}",
        r"\footnotesize",
        rf"\begin{{tabular}}{{{cols}}}",
        r"\toprule",
        group_hdr,
        cmid_hdr,
        " & ".join(["Method"] + [PROB_LABELS[p] for p in PROBS]) + r" \\",
        r"\midrule",
    ]
    for method in METHODS:
        row = [METHOD_LABELS[method]]
        for prob in PROBS:
            e = rt.get(method, {}).get(prob)
            row.append("--" if e is None else fmt_min(e.get("selected_median_min")))
        lines.append(" & ".join(row) + r" \\")
    lines += [r"%\midrule", "%" + tot_line,
              r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    os.makedirs(os.path.dirname(OUT_TEX), exist_ok=True)
    with open(OUT_TEX, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT_TEX}")
    print(f"paper-method totals: {grand_runs} runs, {grand_h:,.0f} CPU-hours")


if __name__ == "__main__":
    main()
